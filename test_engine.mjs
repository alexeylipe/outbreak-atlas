import fs from 'node:fs';
import assert from 'node:assert/strict';
import {Game} from './engine.mjs';
const cfg=JSON.parse(fs.readFileSync(new URL('./balance_v2_5.json',import.meta.url),'utf8'));
cfg.actions_mvp=JSON.parse(fs.readFileSync(new URL('./actions_mvp.json',import.meta.url),'utf8'));
assert.equal(cfg.regions,12);
let a=new Game(cfg,12345),b=new Game(cfg,12345);
assert.deepEqual(a.s,b.s,'Same seed -> same initial state');
for(let i=0;i<20;i++){a.tick();b.tick();}
assert.deepEqual(a.s,b.s,'Same seed -> same ticks');
assert.equal(a.s.regions.length,12);
assert.equal(a.s.regions.filter(r=>r.playable).length,1);
assert.equal(a.s.regions[0].nodes.cloud,1);
assert.equal(a.s.slots.length,2);
const g=new Game(cfg,89);
const first=g.start('small');assert.ok(first.ok);
assert.equal(g.s.compute,9);
const dup=g.start('small');assert.ok(dup.ok);
const queued=g.start('small');assert.ok(queued.ok);
assert.equal(g.s.queue.length,1);
for(let i=0;i<5;i++)g.tick();
assert.ok(g.s.money>40);
assert.ok(g.s.queue.length===0);
const x=new Game(cfg,444), before=x.serialize();
let preview=x.dryRun(['small'],true);
assert.equal(preview.ok,true);
assert.equal(x.s.compute,12,'First dry run free, should not change resource');
assert.equal(x.s.money,40,'Dry run should not change money');
assert.equal(x.s.tick,0,'Dry run should not advance clock');
assert.equal(x.s.regions[0].heat,0,'Dry run should not change heat');
assert.equal(x.s.rng,JSON.parse(before).rng,'Dry run should not mutate main RNG');
assert.equal(x.s.slots.filter(Boolean).length,0,'Dry run should not launch operations');
let bad=x.dryRun(['small'],false);assert.equal(bad.ok,false,'Cooldown enforced');
const h=new Game(cfg,42);h.s.regions[0].heat=100;h.computePressure();assert.ok(h.s.globalHeat<80,'One high region not a global killswitch');
const report={tests:15,success:true,tickSimulation:a.s.tick,generatedBalanceKeyCount:Object.keys(cfg).length};console.log(JSON.stringify(report,null,2));
